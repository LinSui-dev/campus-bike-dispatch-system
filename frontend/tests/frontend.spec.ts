test('关闭 Mock 后通过真实 HTTP 加载停车点或显示骨架 501', async ({ page, request }, info) => {
  const health = await request.get('http://127.0.0.1:18015/api/v1/health')
  expect(health.ok()).toBe(true)
  const { stage } = await health.json()
  const response = page.waitForResponse(res => res.url().endsWith('/api/v1/stations'))
  await page.goto('http://127.0.0.1:15174/')
  await expect(page.locator('.mock-controls')).toHaveCount(0)
  const stations = await response
  if (stage === 'scaffold') {
    expect(stations.status()).toBe(501)
    expect((await stations.json()).code).toBe('NOT_IMPLEMENTED')
    await expect(page.getByRole('alert')).toContainText('业务接口尚未实现')
    await expect(page.getByRole('button', { name: '开始仿真' })).toBeDisabled()
    await expect(page.locator('[data-station]')).toHaveCount(0)
    await shot(page, info, 'real-scaffold-501')
  } else {
    expect(stage).toBe('implemented')
    expect(stations.ok()).toBe(true)
    const { items, total } = await stations.json()
    expect(items).toHaveLength(total)
    await expect(page.locator('[data-station]')).toHaveCount(total)
    await shot(page, info, 'real-fixture-stations')
  }
})

