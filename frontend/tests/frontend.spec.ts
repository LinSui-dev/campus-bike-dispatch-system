interface RequestLog {
  method: string
  path: string
  body?: Record<string, unknown>
}

async function requests(page: Page) {
  return await page.evaluate(() => JSON.parse(sessionStorage.getItem('bike-simulation-fixture-v1-requests') || '[]')) as RequestLog[]
}
const controls = (rows: RequestLog[]) => rows.filter(row => row.method === 'POST' && row.path.endsWith('/control'))
const status = (page: Page) => page.getByTestId('runtime-status')
const actions = (page: Page) => page.locator('.run-actions')
async function go(page: Page, name: string) {
  await page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name, exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name, exact: true })).toBeVisible()
}
async function mockButton(page: Page, name: string) {
  const menu = page.locator('.mock-controls')
  if (!await menu.evaluate(node => (node as HTMLDetailsElement).open)) await menu.locator('summary').click()
  await menu.getByRole('button', { name, exact: true }).click()
  await menu.locator('summary').click()
}
async function shot(page: Page, info: TestInfo, name: string) {
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.screenshot({ path: info.outputPath(name + '.png'), animations: 'disabled', fullPage: true })
}
async function evidence(page: Page, info: TestInfo) {
  await info.attach('fixture-request-log', { body: JSON.stringify(await requests(page), null, 2), contentType: 'application/json' })
}
async function start(page: Page, pause = false) {
  await actions(page).getByRole('button', { name: '开始仿真' }).click()
  await expect(status(page)).toHaveText('运行中')
  if (pause) {
    await actions(page).getByRole('button', { name: '暂停' }).click()
    await expect(status(page)).toHaveText('已暂停')
  }
}

