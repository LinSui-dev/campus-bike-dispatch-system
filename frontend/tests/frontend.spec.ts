async function drag(page: Page, locator: ReturnType<Page['locator']>, dx: number, dy: number) {
  const bounds = await locator.boundingBox()
  if (!bounds) throw new Error('Marker or map is missing')
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2 + dx, bounds.y + bounds.height / 2 + dy, { steps: 9 })
  await page.mouse.up()
}

